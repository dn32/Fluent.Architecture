
CREATE TABLE MXS_LOGDEOPERACOES (
    ID NUMBER GENERATED ALWAYS AS IDENTITY,
    USUARIO VARCHAR2(255) NOT NULL,
    DATA DATE NOT NULL,
    ORIGEM NUMBER NOT NULL,
    METODO VARCHAR2(500) NOT NULL,
    CONSTRAINT PK_MXS_LOGDEOPERACOES
        PRIMARY KEY (ID)
 );

 CREATE TABLE MXS_LOGDEOPERACAOENTIDADES (
    ID NUMBER GENERATED ALWAYS AS IDENTITY,
    LOGDEOPERACAOID NUMBER NOT NULL,
    CHAVES VARCHAR2(500) NOT NULL,
    ENTIDADE VARCHAR2(500) NOT NULL,
    TIPODEOPERACAO NUMBER NOT NULL,

    CONSTRAINT PK_MXS_LOGDEOPERACAOENTIDADES
        PRIMARY KEY (ID),

    CONSTRAINT FK_MXS_LOGDEOPERACAOENTIDADES_MXS_LOGDEOPERACOES
        FOREIGN KEY (LOGDEOPERACAOID)
        REFERENCES MXS_LOGDEOPERACOES (ID)
 );

 CREATE TABLE MXS_LOGDEOPERACAOPROPRIEDADES (
    ID NUMBER GENERATED ALWAYS AS IDENTITY,
    LOGDEOPERACAOENTIDADEID NUMBER NOT NULL,
    NOME VARCHAR2(255) NOT NULL,
    VALORORIGINAL VARCHAR2(4000) NULL,
    NOVOVALOR VARCHAR2(4000) NULL,
    
    CONSTRAINT PK_MXS_LOGDEOPERACAOPROPRIEDADES
        PRIMARY KEY (ID),
    
    CONSTRAINT FK_MXS_LOGDEOPERACAOPROPRIEDADES_MXS_LOGDEOPERACAOENTIDADES
        FOREIGN KEY (LOGDEOPERACAOENTIDADEID)
        REFERENCES MXS_LOGDEOPERACAOENTIDADES (ID)
 );